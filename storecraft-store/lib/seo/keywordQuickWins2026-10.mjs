export function mergeKeywordProductOverrides(base = {}) {
  const out = { ...base };
  for (const [path, row] of Object.entries(KEYWORD_PRODUCT_SEO)) {
    out[path] = {
      ...(out[path] || {}),
      title: row.title,
      meta: row.meta,
    };
  }
  return out;
}

export function mergeKeywordProductFaqs(base = {}) {
  const out = { ...base };
  for (const [path, row] of Object.entries(KEYWORD_PRODUCT_SEO)) {
    if (!row.priceFaq) continue;
    const slug = path.replace(/^\//, "");
    const existing = Array.isArray(out[slug]) ? out[slug] : [];
    const q = row.priceFaq.question.toLowerCase();
    const withoutDup = existing.filter((f) => String(f?.question || "").toLowerCase() !== q);
    out[slug] = [row.priceFaq, ...withoutDup];
  }
  return out;
}
